using System.Text.Json;
using System.Xml.Linq;
using Lore.Models;
using Lore.Services;
using NodaTime;
using UglyToad.PdfPig;

namespace Lore.Tests;

// What the exports say, read back: the words in each PDF, and the numbers in the JSON
// and XML set against the chart they were made from. A file with the right signature
// and the wrong person in it would pass a test that only looked at the first four bytes.
public class ExportContentTests
{
    private static readonly ChartInterpreter Report = new(Repo.Data("interpretations.json"));
    private static readonly DailyInterpreter Daily = new(Repo.Data("daily.json"));
    private static readonly TransitService Transits = new(Repo.Charts);
    private static readonly DateOnly Date = new(2026, 10, 12);

    private static NatalChart Chart(string id) => Repo.Charts.Calculate(Repo.Figure(id));

    // Every word on every page, with the spacing taken out: a PDF places letters, not
    // words, and where one line ends and the next begins is the reader's guess.
    private static string Words(byte[] pdf)
    {
        using var document = PdfDocument.Open(pdf);
        Assert.True(document.NumberOfPages >= 1);
        return Squeeze(string.Concat(document.GetPages().Select(p => p.Text)));
    }

    private static string Squeeze(string text) => string.Concat(text.Where(c => !char.IsWhiteSpace(c)));

    private static void Says(string words, string phrase) =>
        Assert.True(words.Contains(Squeeze(phrase)), $"The PDF does not say: {phrase}");

    private static void DoesNotSay(string words, string phrase) =>
        Assert.False(words.Contains(Squeeze(phrase)), $"The PDF says, and should not: {phrase}");

    // ── The chart's PDF ───────────────────────────────────────────────────────

    [Fact]
    public void The_chart_PDF_carries_this_persons_Report_dignities_and_Worksheet_and_nobody_elses()
    {
        var chart = Chart("elvis-presley");
        var report = Report.Interpret(chart);
        var worksheet = WorksheetService.Build(chart);
        string words = Words(ChartPdf.ToPdf(chart, report, chartPng: [], worksheet));

        Says(words, "Elvis Presley");
        Says(words, chart.Celebrity.BirthPlace);
        Says(words, "Sun Capricorn");
        Says(words, "Rising Sagittarius");
        Says(words, "Chart assessment:");
        DoesNotSay(words, "Marilyn Monroe");

        // Every section of the Report, each with its first paragraph.
        Assert.All(report, section =>
        {
            Says(words, section.Heading);
            Says(words, section.Paragraphs[0]);
        });

        // The dignity table, to the planet; and the Worksheet's sections after it.
        var score = DignityService.Compute(chart);
        Says(words, $"Total {score.Total:+#;-#;0} — {score.Verdict.Label()}");
        Assert.All(score.Planets, p => Says(words, p.Notes));
        Assert.All(worksheet.Sections, section => Says(words, section.Title));
        Says(words, "Generated by Lore");
    }

    [Fact]
    public void An_untimed_chart_PDF_says_what_is_not_known_and_names_both_signs_of_a_Moon_that_changed()
    {
        var person = new Celebrity
        {
            Id = "user-1", Name = "Sam Example", Category = UserChartService.MyChartsCategory,
            BirthDate = "1990-01-01", BirthTimeKnown = false,
            BirthPlace = "Chicago", Latitude = 41.8781, Longitude = -87.6298, TimeZoneId = "America/Chicago",
        };
        var chart = Repo.Charts.Calculate(person);
        var day = TimeSensitivityService.AnalyseDay(Repo.Charts, person)!;
        var report = Report.Interpret(chart, day.MoonSigns, null, day.SignChanges);

        string words = Words(ChartPdf.ToPdf(chart, report, [], WorksheetService.Build(chart), day));

        Says(words, "Sam Example");
        Says(words, "time unknown");
        Says(words, "Moon Aquarius or Pisces");
        Says(words, "not scored — it needs a birth time");
        Says(words, "The Moon changed sign on the day Sam was born");
        DoesNotSay(words, "Rising Sagittarius");   // no rising sign is claimed
        DoesNotSay(words, "Chart Assessment");
    }

    // ── The readings' PDFs ────────────────────────────────────────────────────

    [Fact]
    public void The_daily_PDF_says_what_the_daily_reading_says()
    {
        var chart = Chart("albert-einstein");
        var reading = Daily.Compose(chart, Transits.Scan(chart, Date, DateTimeZone.Utc), DateTimeZone.Utc);
        string words = Words(DailyExportService.ToPdf(reading));

        Says(words, "Albert Einstein");
        Says(words, reading.DateText);
        Assert.All(reading.Sections, s => Says(words, s.Heading));
        Assert.All(reading.Sections.SelectMany(s => s.Items).Where(i => i.HasTitle), i => Says(words, i.Title!));

        // And it is the same reading the text export gives.
        string text = System.Text.Encoding.UTF8.GetString(DailyExportService.ToText(reading));
        Assert.Contains("Albert Einstein", text);
        Assert.All(reading.Sections, s => Assert.Contains(s.Heading.ToUpperInvariant(), text.ToUpperInvariant()));
    }

    [Fact]
    public void The_forecast_and_timing_PDFs_name_the_person_and_carry_every_section()
    {
        var chart = Chart("albert-einstein");
        var forecast = Daily.ComposeForecast(chart, Transits.Forecast(chart, Date, 30, DateTimeZone.Utc), Date, 30, DateTimeZone.Utc);
        string words = Words(DailyExportService.ForecastToPdf(forecast));
        Says(words, "Albert Einstein");
        Assert.NotEmpty(forecast.Sections);
        Assert.All(forecast.Sections, s => Says(words, s.Heading));
        Says(words, forecast.Sections.SelectMany(s => s.Items).First(i => i.HasTitle).Title!);

        var timing = new TimingService(Repo.Charts).Compose(chart, Date, DateTimeZone.Utc);
        words = Words(DailyExportService.TimingToPdf(timing, returnWheelPng: null));
        Says(words, "Albert Einstein");
        Assert.All(timing.Sections, s => Says(words, s.Heading));
    }

    [Fact]
    public void The_synastry_and_Davison_PDFs_name_both_people_in_the_order_they_were_compared()
    {
        var elvis = Chart("elvis-presley");
        var marilyn = Chart("marilyn-monroe");
        var between = Repo.Charts.Davison(elvis, marilyn);
        var synastry = SynastryService.Compare(elvis, marilyn, between);

        var reading = new SynastryInterpreter(Repo.Data("synastry.json")).Compose(synastry);
        string words = Words(SynastryExportService.ToPdf(synastry, reading, wheelPng: []));
        Says(words, "Elvis Presley");
        Says(words, "Marilyn Monroe");
        Assert.All(reading.Sections, s => Says(words, s.Heading));
        DoesNotSay(words, "Albert Einstein");

        var davison = new DavisonInterpreter(Repo.Data("davison.json")).Compose(synastry)!;
        words = Words(SynastryExportService.DavisonToPdf(synastry, davison, [], WorksheetService.Build(davison.Chart)));
        Says(words, "Elvis Presley");
        Says(words, "Marilyn Monroe");
        Assert.All(davison.Sections, s => Says(words, s.Heading));
    }

    // ── The data exports ──────────────────────────────────────────────────────

    [Fact]
    public void The_JSON_export_holds_the_chart_it_was_made_from_number_for_number()
    {
        var chart = Chart("elvis-presley");
        chart.Events = NatalEventsService.Compute(Repo.Charts, chart);
        using var json = JsonDocument.Parse(ChartDataExport.ToJson(chart));
        var root = json.RootElement;

        Assert.Equal("Lore", root.GetProperty("GeneratedBy").GetString());
        Assert.Equal("Elvis Presley", root.GetProperty("Name").GetString());
        Assert.Equal(chart.Celebrity.BirthDate, root.GetProperty("BirthDate").GetString());
        Assert.Equal(chart.Celebrity.BirthPlace, root.GetProperty("BirthPlace").GetString());
        Assert.Equal(Math.Round(chart.Ascendant, 4), root.GetProperty("Ascendant").GetDouble(), 4);
        Assert.Equal(Math.Round(chart.Midheaven, 4), root.GetProperty("Midheaven").GetDouble(), 4);
        Assert.Equal("Sagittarius", root.GetProperty("AscendantSign").GetString());

        // Every body, at its longitude, in its sign and house.
        var planets = root.GetProperty("Planets").EnumerateArray().ToList();
        Assert.Equal(chart.Planets.Select(p => p.PlanetName), planets.Select(p => p.GetProperty("Name").GetString()));
        foreach (var (given, body) in planets.Zip(chart.Planets))
        {
            Assert.InRange(Math.Abs(body.Longitude - given.GetProperty("Longitude").GetDouble()), 0, 0.0001);
            Assert.Equal(body.Sign.Name(), given.GetProperty("Sign").GetString());
            Assert.Equal(chart.GetHouseForLongitude(body.Longitude), given.GetProperty("House").GetInt32());
            Assert.Equal(body.IsRetrograde, given.GetProperty("Retrograde").GetBoolean());
        }

        Assert.Equal(12, root.GetProperty("Houses").GetArrayLength());
        // Planet to planet, planet to angle, and planet to the Vertex, Fortune and Spirit.
        Assert.Equal(chart.Aspects.Count + chart.AngleAspects.Count + WorksheetService.PointAspects(chart).Count,
            root.GetProperty("Aspects").GetArrayLength());
        Assert.Equal(DignityService.Compute(chart).Total, root.GetProperty("Dignity").GetProperty("Total").GetInt32());
        Assert.Equal(2, root.GetProperty("Lunations").GetArrayLength());

        // The same instant the Worksheet prints.
        string worksheet = System.Text.Encoding.UTF8.GetString(WorksheetService.ToText(WorksheetService.Build(chart)));
        string julianDay = root.GetProperty("JulianDay").GetDouble().ToString("0.00000", System.Globalization.CultureInfo.InvariantCulture);
        Assert.Contains(julianDay, worksheet);
    }

    [Fact]
    public void The_XML_export_says_the_same_as_the_JSON()
    {
        var chart = Chart("marilyn-monroe");
        using var json = JsonDocument.Parse(ChartDataExport.ToJson(chart));
        var xml = XDocument.Parse(System.Text.Encoding.UTF8.GetString(ChartDataExport.ToXml(chart)));
        var root = xml.Root!;

        Assert.Equal("ChartExport", root.Name.LocalName);
        Assert.Equal("Marilyn Monroe", root.Element("Name")!.Value);
        var fromXml = root.Element("Planets")!.Elements().Select(p => (p.Element("Name")!.Value, p.Element("Sign")!.Value,
            double.Parse(p.Element("Longitude")!.Value, System.Globalization.CultureInfo.InvariantCulture))).ToList();
        var fromJson = json.RootElement.GetProperty("Planets").EnumerateArray().Select(p => (p.GetProperty("Name").GetString()!,
            p.GetProperty("Sign").GetString()!, p.GetProperty("Longitude").GetDouble())).ToList();
        Assert.Equal(fromJson, fromXml);
        Assert.Equal(json.RootElement.GetProperty("Aspects").GetArrayLength(), root.Element("Aspects")!.Elements().Count());
        Assert.Equal(json.RootElement.GetProperty("AscendantSign").GetString(), root.Element("AscendantSign")!.Value);
    }

    [Fact]
    public void Without_a_birth_time_the_data_export_leaves_out_what_cannot_be_known()
    {
        var chart = Repo.Charts.Calculate(Demo.Person(timed: false));
        using var json = JsonDocument.Parse(ChartDataExport.ToJson(chart));
        var root = json.RootElement;

        Assert.False(root.GetProperty("BirthTimeKnown").GetBoolean());
        Assert.Equal(JsonValueKind.Null, root.GetProperty("Ascendant").ValueKind);
        Assert.Equal(JsonValueKind.Null, root.GetProperty("Midheaven").ValueKind);
        Assert.Equal(JsonValueKind.Null, root.GetProperty("Dignity").ValueKind);
        Assert.Equal(0, root.GetProperty("Houses").GetArrayLength());
        Assert.All(root.GetProperty("Planets").EnumerateArray(), p => Assert.Equal(JsonValueKind.Null, p.GetProperty("House").ValueKind));
        Assert.Equal(chart.Planets.Count, root.GetProperty("Planets").GetArrayLength());
    }
}
